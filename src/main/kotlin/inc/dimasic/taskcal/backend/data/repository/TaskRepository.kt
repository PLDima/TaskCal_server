package inc.dimasic.taskcal.backend.data.repository

import inc.dimasic.taskcal.backend.data.nowUtc
import inc.dimasic.taskcal.backend.data.table.Tasks
import inc.dimasic.taskcal.backend.domain.model.Task
import org.jetbrains.exposed.v1.core.ResultRow
import org.jetbrains.exposed.v1.core.SortOrder
import org.jetbrains.exposed.v1.core.and
import org.jetbrains.exposed.v1.core.eq
import org.jetbrains.exposed.v1.core.statements.UpdateBuilder
import org.jetbrains.exposed.v1.jdbc.Database
import org.jetbrains.exposed.v1.jdbc.deleteWhere
import org.jetbrains.exposed.v1.jdbc.insert
import org.jetbrains.exposed.v1.jdbc.select
import org.jetbrains.exposed.v1.jdbc.selectAll
import org.jetbrains.exposed.v1.jdbc.transactions.suspendTransaction
import org.jetbrains.exposed.v1.jdbc.update
import kotlin.uuid.Uuid

class TaskRepository(private val db: Database) {

    suspend fun list(userId: Uuid): List<Task> = suspendTransaction(db) {
        Tasks.selectAll()
            .where { Tasks.userId eq userId }
            .orderBy(Tasks.createdAt to SortOrder.ASC, Tasks.id to SortOrder.ASC)
            .map { it.toTask() }
    }

    suspend fun find(userId: Uuid, taskId: Uuid): Task? = suspendTransaction(db) {
        Tasks.selectAll()
            .where { (Tasks.id eq taskId) and (Tasks.userId eq userId) }
            .singleOrNull()
            ?.toTask()
    }

    /**
     * Inserts or replaces [task] for [userId]. Task ids are generated by the client, so an id can
     * already exist for someone else — then nothing is written and this returns false.
     */
    suspend fun save(userId: Uuid, task: Task): Boolean = suspendTransaction(db) {
        val owner = Tasks.select(Tasks.userId).where { Tasks.id eq task.id }.singleOrNull()?.get(Tasks.userId)
        when (owner) {
            null -> Tasks.insert {
                it[Tasks.id] = task.id
                it[Tasks.userId] = userId
                it.write(task)
            }

            userId -> Tasks.update({ Tasks.id eq task.id }) {
                it.write(task)
                it[Tasks.updatedAt] = nowUtc()
            }

            else -> return@suspendTransaction false
        }
        true
    }

    suspend fun delete(userId: Uuid, taskId: Uuid): Boolean = suspendTransaction(db) {
        Tasks.deleteWhere { (Tasks.id eq taskId) and (Tasks.userId eq userId) } > 0
    }

    private fun UpdateBuilder<*>.write(task: Task) {
        this[Tasks.title] = task.title
        this[Tasks.description] = task.description
        this[Tasks.priority] = task.priority
        this[Tasks.recurrenceType] = task.recurrenceType
        this[Tasks.repeatDayOfWeek] = task.repeatDayOfWeek
        this[Tasks.repeatDayOfMonth] = task.repeatDayOfMonth
        this[Tasks.assignedDateTime] = task.assignedDateTime
        this[Tasks.hasDueTime] = task.hasDueTime
        this[Tasks.isCompleted] = task.isCompleted
    }

    private fun ResultRow.toTask() = Task(
        id = this[Tasks.id],
        title = this[Tasks.title],
        description = this[Tasks.description],
        priority = this[Tasks.priority],
        recurrenceType = this[Tasks.recurrenceType],
        repeatDayOfWeek = this[Tasks.repeatDayOfWeek],
        repeatDayOfMonth = this[Tasks.repeatDayOfMonth],
        assignedDateTime = this[Tasks.assignedDateTime],
        hasDueTime = this[Tasks.hasDueTime],
        isCompleted = this[Tasks.isCompleted],
    )
}
